"""Tool result persistence -- preserves large outputs instead of truncating.

Defense against context-window overflow operates at three levels:

1. **Per-tool output cap** (inside each tool): Tools like search_files
   pre-truncate their own output before returning. This is the first line
   of defense and the only one the tool author controls.

2. **Per-result persistence** (maybe_persist_tool_result): After a tool
   returns, if its output exceeds the tool's registered threshold
   (registry.get_max_result_size), the full output is written INTO THE
   SANDBOX temp dir (for example /tmp/youtab-results/{tool_use_id}.txt on
   standard Linux, or $TMPDIR/youtab-results/{tool_use_id}.txt on Termux)
   via env.execute(). The in-context content is replaced with a preview +
   file path reference. The model can read_file to access the full output
   on any backend.

3. **Per-turn aggregate budget** (enforce_turn_budget): After all tool
   results in a single assistant turn are collected, if the total exceeds
   MAX_TURN_BUDGET_CHARS (200K), the largest non-persisted results are
   spilled to disk until the aggregate is under budget. This catches cases
   where many medium-sized results combine to overflow context.
"""

import hashlib
import logging
import os
import re
import shlex
import uuid

from tools.budget_config import (
    DEFAULT_PREVIEW_SIZE_CHARS,
    BudgetConfig,
    DEFAULT_BUDGET,
)

logger = logging.getLogger(__name__)
PERSISTED_OUTPUT_TAG = "<persisted-output>"
PERSISTED_OUTPUT_CLOSING_TAG = "</persisted-output>"
STORAGE_DIR = "/tmp/youtab-results"
HEREDOC_MARKER = "YOUTAB_AGENT_PERSIST_EOF"
_BUDGET_TOOL_NAME = "__budget_enforcement__"
_UNSAFE_RESULT_FILENAME_CHARS = re.compile(r"[^A-Za-z0-9_.-]+")
_MAX_RESULT_FILENAME_STEM = 120

# Per-run spill isolation (ADR-0005 §7a). The spill root is scoped by an opaque,
# Runtime-generated run/execution id so two runs using the same tool_use_id cannot
# overwrite or read each other's results, and no tenant/user/model string can
# select another run's scope.
_SAFE_SCOPE = re.compile(r"[A-Za-z0-9_-]{1,64}")
_RESULT_SCOPE_ATTR = "_youtab_result_scope"
# Bound a single result spill so one write can never be unbounded.
MAX_SPILL_BYTES = 20 * 1024 * 1024


def _run_scope(env) -> str | None:
    """Return the opaque, Runtime-generated per-run spill scope for ``env``.

    Prefers the environment's own ``_session_id`` (generated by
    ``BaseEnvironment``, bound to the run's lifecycle); otherwise a lazily
    generated opaque id cached on the env. The scope is NEVER derived from
    tenant/user/model-supplied input, so a caller can never select another run's
    scope; distinct runs (distinct env instances) get distinct, unguessable
    scopes. Returns ``None`` when there is no env (the caller then inline
    truncates)."""
    if env is None:
        return None
    sid = getattr(env, "_session_id", None)
    if isinstance(sid, str) and _SAFE_SCOPE.fullmatch(sid):
        return f"run-{sid}"
    scope = getattr(env, _RESULT_SCOPE_ATTR, None)
    if isinstance(scope, str) and scope:
        return scope
    scope = "run-" + uuid.uuid4().hex
    try:
        setattr(env, _RESULT_SCOPE_ATTR, scope)
    except Exception:
        pass
    return scope


def _spill_dir(env) -> str | None:
    """The per-run spill directory ``{store-root}/{run-scope}`` or ``None``."""
    scope = _run_scope(env)
    if scope is None:
        return None
    return f"{_resolve_storage_dir(env)}/{scope}"


def _resolve_storage_dir(env) -> str:
    """Return the best temp-backed storage dir for this environment."""
    if env is not None:
        get_temp_dir = getattr(env, "get_temp_dir", None)
        if callable(get_temp_dir):
            try:
                temp_dir = get_temp_dir()
            except Exception as exc:
                logger.debug("Could not resolve env temp dir: %s", exc)
            else:
                if temp_dir:
                    temp_dir = temp_dir.rstrip("/") or "/"
                    return f"{temp_dir}/youtab-results"
    return STORAGE_DIR


def _safe_result_filename(tool_use_id: str) -> str:
    """Return a single safe filename for a tool result id."""
    raw_id = str(tool_use_id or "tool_result")
    safe_stem = _UNSAFE_RESULT_FILENAME_CHARS.sub("_", raw_id).strip("._-")
    changed = safe_stem != raw_id

    if not safe_stem:
        safe_stem = "tool_result"
        changed = True

    if changed or len(safe_stem) > _MAX_RESULT_FILENAME_STEM:
        digest = hashlib.sha256(raw_id.encode("utf-8")).hexdigest()[:12]
        safe_stem = safe_stem[:_MAX_RESULT_FILENAME_STEM].rstrip("._-") or "tool_result"
        safe_stem = f"{safe_stem}_{digest}"

    return f"{safe_stem}.txt"


def generate_preview(content: str, max_chars: int = DEFAULT_PREVIEW_SIZE_CHARS) -> tuple[str, bool]:
    """Truncate at last newline within max_chars. Returns (preview, has_more)."""
    if len(content) <= max_chars:
        return content, False
    truncated = content[:max_chars]
    last_nl = truncated.rfind("\n")
    if last_nl > max_chars // 2:
        truncated = truncated[:last_nl + 1]
    return truncated, True


def _heredoc_marker(content: str) -> str:
    """Return a heredoc delimiter that doesn't collide with content."""
    if HEREDOC_MARKER not in content:
        return HEREDOC_MARKER
    return f"YOUTAB_AGENT_PERSIST_{uuid.uuid4().hex[:8]}"


def _write_to_sandbox(content: str, remote_path: str, env) -> bool:
    """Write content into the sandbox via env.execute(). Returns True on success.

    Pushes ``content`` through stdin rather than embedding it in the command
    string. Linux's ``MAX_ARG_STRLEN`` caps any single argv element at 128 KB
    (32 * PAGE_SIZE), so the previous heredoc-in-the-command-string approach
    silently failed with ``OSError: [Errno 7] Argument list too long`` for any
    tool result over ~128 KB — exactly the case persistence exists to handle.
    Routing through stdin removes that ceiling on local + ssh (``_stdin_mode
    == "pipe"``); remote backends with ``_stdin_mode == "heredoc"`` keep their
    existing API-body sized limit, which is orders of magnitude larger than
    the exec-arg ceiling.
    """
    storage_dir = os.path.dirname(remote_path)
    parent_dir = os.path.dirname(storage_dir)
    # Containment invariant (ADR-0005 §7a — allow-listed internal-plane writer):
    # the result-store write MUST target a single sanitized filename directly
    # inside the run-scoped spill dir — never a nested path or a parent-directory
    # traversal. ``tool_use_id`` is the only attacker-influenceable input to the
    # path and is already sanitized by ``_safe_result_filename``; enforcing it
    # here makes containment an EXPLICIT, testable invariant at the write
    # chokepoint. Fail closed (no write) on any violation — the caller then falls
    # back to inline truncation.
    leaf = os.path.basename(remote_path.replace("\\", "/"))
    if not leaf or leaf in (".", "..") or "/" in leaf or "\\" in leaf:
        logger.warning(
            "Refusing result-store write with an unsafe filename component: %r",
            remote_path,
        )
        return False
    # Every infrastructure-controlled path is shell-quoted with the canonical
    # POSIX quoter; content travels ONLY through stdin, never argv/interpolation.
    # A restrictive umask + explicit 0700 dir / 0600 file keep the spill private,
    # and each path component (store root, spill dir, leaf) is rejected if it is a
    # pre-existing symlink so a hostile reparse target cannot redirect the write.
    # On a non-POSIX backend these builtins are unavailable → the command fails →
    # the caller falls back to inline truncation (fail closed). This is
    # shell-level protection for the sandbox filesystem; it does NOT claim
    # host-handle-level containment for a remote backend.
    q_parent = shlex.quote(parent_dir)
    q_dir = shlex.quote(storage_dir)
    q_path = shlex.quote(remote_path)
    cmd = (
        "umask 077; "
        f"if [ -L {q_parent} ]; then echo 'result-store root is a symlink' >&2; exit 90; fi; "
        f"if [ -L {q_dir} ]; then echo 'spill dir is a symlink' >&2; exit 91; fi; "
        f"mkdir -p {q_dir} && chmod 700 {q_dir} || exit 93; "
        f"if [ -L {q_path} ]; then echo 'spill target is a symlink' >&2; exit 92; fi; "
        f"cat > {q_path} && chmod 600 {q_path}"
    )
    result = env.execute(cmd, timeout=30, stdin_data=content)
    return result.get("returncode", 1) == 0


def _build_persisted_message(
    preview: str,
    has_more: bool,
    original_size: int,
    file_path: str,
) -> str:
    """Build the <persisted-output> replacement block."""
    size_kb = original_size / 1024
    if size_kb >= 1024:
        size_str = f"{size_kb / 1024:.1f} MB"
    else:
        size_str = f"{size_kb:.1f} KB"

    msg = f"{PERSISTED_OUTPUT_TAG}\n"
    msg += f"This tool result was too large ({original_size:,} characters, {size_str}).\n"
    msg += f"Full output saved to: {file_path}\n"
    msg += "Use the read_file tool with offset and limit to access specific sections of this output.\n\n"
    msg += f"Preview (first {len(preview)} chars):\n"
    msg += preview
    if has_more:
        msg += "\n..."
    msg += f"\n{PERSISTED_OUTPUT_CLOSING_TAG}"
    return msg


def maybe_persist_tool_result(
    content: str,
    tool_name: str,
    tool_use_id: str,
    env=None,
    config: BudgetConfig = DEFAULT_BUDGET,
    threshold: int | float | None = None,
) -> str:
    """Layer 2: persist oversized result into the sandbox, return preview + path.

    Writes via env.execute() so the file is accessible from any backend
    (local, Docker, SSH, Modal, Daytona). Falls back to inline truncation
    if write fails or no env is available.

    Args:
        content: Raw tool result string.
        tool_name: Name of the tool (used for threshold lookup).
        tool_use_id: Unique ID for this tool call (used as filename).
        env: The active BaseEnvironment instance, or None.
        config: BudgetConfig controlling thresholds and preview size.
        threshold: Explicit override; takes precedence over config resolution.

    Returns:
        Original content if small, or <persisted-output> replacement.
    """
    effective_threshold = threshold if threshold is not None else config.resolve_threshold(tool_name)

    if effective_threshold == float("inf"):
        return content

    if len(content) <= effective_threshold:
        return content

    spill_dir = _spill_dir(env)
    preview, has_more = generate_preview(content, max_chars=config.preview_size)

    if spill_dir is not None:
        remote_path = f"{spill_dir}/{_safe_result_filename(tool_use_id)}"
        # Bound the spill: a single result never writes more than MAX_SPILL_BYTES.
        spill_content = (
            content if len(content) <= MAX_SPILL_BYTES else content[:MAX_SPILL_BYTES]
        )
        try:
            if _write_to_sandbox(spill_content, remote_path, env):
                logger.info(
                    "Persisted large tool result: %s (%s, %d chars -> %s%s)",
                    tool_name, tool_use_id, len(content), remote_path,
                    " [capped]" if len(spill_content) < len(content) else "",
                )
                return _build_persisted_message(preview, has_more, len(content), remote_path)
        except Exception as exc:
            logger.warning("Sandbox write failed for %s: %s", tool_use_id, exc)

    logger.info(
        "Inline-truncating large tool result: %s (%d chars, no sandbox write)",
        tool_name, len(content),
    )
    return (
        f"{preview}\n\n"
        f"[Truncated: tool response was {len(content):,} chars. "
        f"Full output could not be saved to sandbox.]"
    )


def cleanup_run_scope(env) -> bool:
    """Deterministically remove ONLY the current run's spill scope directory.

    Call this at run / session shutdown (bind it to the existing environment
    teardown). Removal is strictly limited to ``{store-root}/{run-scope}``: the
    target must be a direct child of the store root and must not be a symlink, so
    a cleanup failure or a hostile pre-existing symlink can NEVER delete
    user/workspace files. Returns ``True`` on success.

    For container / remote backends the whole sandbox temp is discarded on
    teardown; this is the explicit cleanup for the local backend where the store
    persists in the host temp. Abnormal-termination fallback: the scope dir lives
    under the environment's own temp dir, which the backend / OS reclaims when the
    session ends.
    """
    if env is None:
        return False
    scope = _run_scope(env)
    if not scope or "/" in scope or "\\" in scope or scope in (".", ".."):
        return False
    root = _resolve_storage_dir(env)
    spill_dir = f"{root}/{scope}"
    # Containment: spill_dir must be exactly {root}/{single-component scope}.
    if os.path.dirname(spill_dir.replace("\\", "/")) != root.replace("\\", "/"):
        return False
    q_root = shlex.quote(root)
    q_spill = shlex.quote(spill_dir)
    # Shell-level containment guard (defence in depth) before rm -rf: the target
    # must be inside the store root and must not be a symlink.
    cmd = (
        f"case {q_spill} in {q_root}/*) : ;; *) echo 'refusing out-of-root cleanup' >&2; exit 94 ;; esac; "
        f"if [ -L {q_spill} ]; then echo 'refusing symlink cleanup' >&2; exit 95; fi; "
        f"rm -rf -- {q_spill}"
    )
    try:
        result = env.execute(cmd, timeout=30)
    except Exception as exc:  # a cleanup failure never propagates / never over-deletes
        logger.warning("Result-store cleanup failed for scope %s: %s", scope, exc)
        return False
    return result.get("returncode", 1) == 0


def enforce_turn_budget(
    tool_messages: list[dict],
    env=None,
    config: BudgetConfig = DEFAULT_BUDGET,
) -> list[dict]:
    """Layer 3: enforce aggregate budget across all tool results in a turn.

    If total chars exceed budget, persist the largest non-persisted results
    first (via sandbox write) until under budget. Already-persisted results
    are skipped.

    Mutates the list in-place and returns it.
    """
    candidates = []
    total_size = 0
    for i, msg in enumerate(tool_messages):
        content = msg.get("content", "")
        size = len(content)
        total_size += size
        if PERSISTED_OUTPUT_TAG not in content:
            candidates.append((i, size))

    if total_size <= config.turn_budget:
        return tool_messages

    candidates.sort(key=lambda x: x[1], reverse=True)

    for idx, size in candidates:
        if total_size <= config.turn_budget:
            break
        msg = tool_messages[idx]
        content = msg["content"]
        tool_use_id = msg.get("tool_call_id", f"budget_{idx}")

        replacement = maybe_persist_tool_result(
            content=content,
            tool_name=_BUDGET_TOOL_NAME,
            tool_use_id=tool_use_id,
            env=env,
            config=config,
            threshold=0,
        )
        if replacement != content:
            total_size -= size
            total_size += len(replacement)
            tool_messages[idx]["content"] = replacement
            logger.info(
                "Budget enforcement: persisted tool result %s (%d chars)",
                tool_use_id, size,
            )

    return tool_messages
