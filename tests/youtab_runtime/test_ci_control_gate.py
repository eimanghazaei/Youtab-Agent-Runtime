"""Every condition in the CI-control gate must actually fire.

A gate that audits other gates is only worth having if each of its own
conditions is known to detect the thing it names. Each test below builds the
defect as a real workflow or baseline on disk and asserts the condition
reports it -- and, as importantly, that the healthy shape does not trip it,
because a control that cries wolf is deleted rather than fixed.

The two conditions that need the GitHub API (a required check nobody
produces, and a gate nothing requires) are covered for their SKIP behaviour
only: they must report as skipped rather than passing, which is what
AGENTS.md requires of a blocked check.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
GATE_PATH = REPO_ROOT / "scripts" / "youtab" / "ci_control_gate.py"


@pytest.fixture(scope="module")
def gate():
    pytest.importorskip("yaml")
    assert GATE_PATH.is_file(), f"missing {GATE_PATH}"
    spec = importlib.util.spec_from_file_location("ci_control_gate", GATE_PATH)
    module = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(GATE_PATH.parent))
    try:
        spec.loader.exec_module(module)
    finally:
        sys.path.remove(str(GATE_PATH.parent))
    return module


HEALTHY = """\
name: ci
on:
  pull_request:
permissions:
  contents: read
jobs:
  build:
    name: build
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
      - name: test
        run: pytest -q
"""


def write_workflow(root: Path, name: str, body: str) -> Path:
    directory = root / ".github" / "workflows"
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    path.write_text(body, encoding="utf-8")
    return path


def conditions(gate, root: Path, *, checks) -> list[str]:
    """Run one or more conditions over `root` and return the failed names."""
    findings = gate.Findings()
    workflows = gate.load_workflows(root)
    for check in checks:
        if check is gate.check_codeql_coherence:
            check(root, workflows, findings)
        else:
            check(workflows, findings)
    return [item["condition"] for item in findings.failures]


def test_a_healthy_workflow_trips_nothing(gate, tmp_path):
    """The false-positive guard. Without this the rest is unfalsifiable."""
    write_workflow(tmp_path, "ci.yml", HEALTHY)
    failed = conditions(gate, tmp_path, checks=[
        gate.check_action_pins,
        gate.check_permissions,
        gate.check_pull_request_target,
        gate.check_gates_can_fail,
    ])
    assert failed == [], failed


def test_an_unpinned_action_is_reported(gate, tmp_path):
    """A floating tag changes what runs in CI with no commit here."""
    write_workflow(tmp_path, "ci.yml",
                   HEALTHY.replace("actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1",
                                   "actions/checkout@v4"))
    assert "unpinned action" in conditions(gate, tmp_path,
                                          checks=[gate.check_action_pins])


def test_a_pin_without_a_version_comment_is_reported(gate, tmp_path):
    """A bare 40-character SHA is unreviewable without resolving it."""
    write_workflow(tmp_path, "ci.yml", HEALTHY.replace(" # v7.0.1", ""))
    assert "pin without a version comment" in conditions(
        gate, tmp_path, checks=[gate.check_action_pins])


def test_two_refs_for_one_codeql_subaction_are_reported(gate, tmp_path):
    """dependabot's #74 shape, which the first version of this test blessed.

    It bumped `github/codeql-action/init` to 4.38.2 and left `analyze` on
    3.37.9. Since 3.30.4 the non-init steps THROW when they load a config
    generated by a different version, so every run dies at `analyze` with no
    SARIF.

    The first version of this test asserted that was FINE, because the gate
    keyed on the full action path and put `init` and `analyze` in separate
    buckets with one ref each. Keying on the REPOSITORY is what makes the
    condition detect the thing it was written for.
    """
    matched = HEALTHY + """\
      - uses: github/codeql-action/init@2892aa5e19bbd11bc0cff5427e3b750a04d9e3c2 # v4.38.2
      - uses: github/codeql-action/analyze@2892aa5e19bbd11bc0cff5427e3b750a04d9e3c2 # v4.38.2
"""
    write_workflow(tmp_path, "ci.yml", matched)
    assert conditions(gate, tmp_path, checks=[gate.check_action_pins]) == []

    split = matched.replace(
        "analyze@2892aa5e19bbd11bc0cff5427e3b750a04d9e3c2 # v4.38.2",
        "analyze@6f5948dfacef28e207b48d0905cf90c03365536d # v3.37.9",
    )
    write_workflow(tmp_path, "ci.yml", split)
    assert "split action version" in conditions(
        gate, tmp_path, checks=[gate.check_action_pins]
    ), "init and analyze are sub-actions of ONE repository and must share a release"


def test_two_different_repositories_at_different_refs_are_fine(gate, tmp_path):
    """The false-positive guard for the repository keying.

    `actions/checkout` and `actions/upload-artifact` are separate
    repositories that legitimately sit at different versions; grouping by
    owner alone would flag them.
    """
    body = HEALTHY + """\
      - uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02 # v4
"""
    write_workflow(tmp_path, "ci.yml", body)
    assert conditions(gate, tmp_path, checks=[gate.check_action_pins]) == []


def test_an_unpinned_reusable_workflow_call_is_reported(gate, tmp_path):
    """Job-level `uses:` is a reusable workflow, not a step.

    `jobs.<id>.uses: owner/repo/.github/workflows/ci.yml@main` never appears
    in `job.steps`, so iterating steps alone omitted it from the audit
    entirely -- and it runs with this repository's token.
    """
    write_workflow(tmp_path, "ci.yml", """\
name: ci
on:
  pull_request:
permissions:
  contents: read
jobs:
  call:
    uses: some-org/shared/.github/workflows/build.yml@main
""")
    failed = conditions(gate, tmp_path, checks=[gate.check_action_pins])
    assert "unpinned action" in failed, failed


