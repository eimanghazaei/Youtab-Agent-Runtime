def test_pull_request_target_with_a_pr_head_checkout_is_reported(gate, tmp_path):
    """The standard CI takeover, which nothing else here looked for."""
    body = HEALTHY.replace("  pull_request:\n", "  pull_request_target:\n").replace(
        "      - name: test",
        "        with:\n"
        "          ref: ${{ github.event.pull_request.head.sha }}\n"
        "      - name: test",
    )
    write_workflow(tmp_path, "ci.yml", body)
    assert "pull_request_target checks out PR head" in conditions(
        gate, tmp_path, checks=[gate.check_pull_request_target])


