def test_missing_permissions_is_reported(gate, tmp_path):
    """No `permissions:` block means the token inherits the repo default."""
    write_workflow(tmp_path, "ci.yml",
                   HEALTHY.replace("permissions:\n  contents: read\n", ""))
    assert "missing permissions" in conditions(
        gate, tmp_path, checks=[gate.check_permissions])


def test_a_job_without_permissions_is_reported_even_when_a_sibling_has_them(
    gate, tmp_path
):
    """Job-level permissions configure jobs INDEPENDENTLY.

    With no workflow-level block and one job declaring its own, the earlier
    `any(...)` form reported the whole workflow as protected -- while the
    other job still received the repository default, which can be write-all.
    """
    write_workflow(tmp_path, "ci.yml", """\
name: ci
on:
  pull_request:
jobs:
  guarded:
    permissions:
      contents: read
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
  uncovered:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
""")
    findings = gate.Findings()
    gate.check_permissions(gate.load_workflows(tmp_path), findings)
    reported = [(i["condition"], i["where"]) for i in findings.failures]
    assert any(c == "missing permissions" and w.endswith(":uncovered")
               for c, w in reported), reported
    assert not any(w.endswith(":guarded") for _c, w in reported), reported


