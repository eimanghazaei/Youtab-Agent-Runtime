# ---------------------------------------------------------------------------
# The CodeQL coherence conditions run against a synthetic tree, so they need
# the gate module importable from `scripts/youtab` -- which is why `root` is
# the real repository here and only the baselines are redirected.
# ---------------------------------------------------------------------------
def test_the_real_repository_passes_every_offline_condition(gate):
    """The conditions must hold for this repository as it stands.

    This is the one test that would have caught the state the gate was written
    for, and it is also the regression guard: a later change to a workflow, a
    pin, or a baseline that breaks a condition fails here rather than in CI.
    """
    findings = gate.Findings()
    workflows = gate.load_workflows(REPO_ROOT)
    assert workflows, "no workflows found in the repository"
    gate.check_action_pins(workflows, findings)
    gate.check_permissions(workflows, findings)
    gate.check_pull_request_target(workflows, findings)
    gate.check_gates_can_fail(workflows, findings)
    gate.check_codeql_coherence(REPO_ROOT, workflows, findings)
    assert findings.failures == [], json.dumps(findings.failures, indent=2)


def test_the_required_checks_condition_skips_rather_than_passes(gate, monkeypatch):
    """AGENTS.md: a blocked check must not become a PASS.

    Without a token the ruleset cannot be read. The condition must say so --
    reported as SKIPPED and counted separately -- and `--require-remote` must
    turn that into a failure for CI, where the token exists and a skip would
    mean the check silently stopped running.
    """
    monkeypatch.delenv("GH_TOKEN", raising=False)
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)

    findings = gate.Findings()
    gate.check_required_checks(REPO_ROOT, {}, "owner/repo", findings, False)
    assert findings.failures == []
    assert len(findings.skips) == 1
    assert "NOT evaluated" in findings.skips[0]["detail"]

    strict = gate.Findings()
    gate.check_required_checks(REPO_ROOT, {}, "owner/repo", strict, True)
    assert [i["condition"] for i in strict.failures] == ["ruleset unavailable"]


def test_a_codeql_leg_without_a_baseline_is_reported(gate, tmp_path, monkeypatch):
    """The gate step would otherwise fail every run with a path error."""
    root = tmp_path
    (root / "scripts" / "youtab" / "codeql_baselines").mkdir(parents=True)
    for name in ("codeql_sarif_gate.py", "regenerate_codeql_baseline.py"):
        (root / "scripts" / "youtab" / name).write_bytes(
            (REPO_ROOT / "scripts" / "youtab" / name).read_bytes()
        )
    write_workflow(root, "codeql.yml", """\
name: CodeQL
on:
  pull_request:
permissions:
  contents: read
jobs:
  analyze:
    name: CodeQL analyze (${{ matrix.language }})
    runs-on: ubuntu-latest
    strategy:
      matrix:
        include:
          - language: python
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
""")
    findings = gate.Findings()
    gate.check_codeql_coherence(root, gate.load_workflows(root), findings)
    assert "codeql leg without a baseline" in [
        i["condition"] for i in findings.failures
    ], findings.failures


def test_a_baseline_without_a_severity_budget_is_reported(gate, tmp_path):
    """The ratchet lives in the baseline, so a missing budget removes it."""
    root = tmp_path
    baselines = root / "scripts" / "youtab" / "codeql_baselines"
    baselines.mkdir(parents=True)
    for name in ("codeql_sarif_gate.py", "regenerate_codeql_baseline.py"):
        (root / "scripts" / "youtab" / name).write_bytes(
            (REPO_ROOT / "scripts" / "youtab" / name).read_bytes()
        )
    (baselines / "python.json").write_text(json.dumps({
        "source_run": "https://example.test/run/1",
        "source_head": "0" * 40,
        "artifact_count": 1, "query_count": 1, "extracted_count": 1,
    }), encoding="utf-8")
    write_workflow(root, "codeql.yml", """\
name: CodeQL
on:
  pull_request:
permissions:
  contents: read
jobs:
  analyze:
    name: CodeQL analyze (${{ matrix.language }})
    runs-on: ubuntu-latest
    strategy:
      matrix:
        include:
          - language: python
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
""")
    findings = gate.Findings()
    gate.check_codeql_coherence(root, gate.load_workflows(root), findings)
    reported = [i["condition"] for i in findings.failures]
    assert "baseline without a severity budget" in reported, findings.failures
